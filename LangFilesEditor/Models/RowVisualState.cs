namespace LangFilesEditor.Models;

/// <summary>
/// Визуальное состояние строки грида записи перевода (без привязки к конкретному цвету/кисти WPF).
/// </summary>
public enum RowVisualState
{
    // todo: и всё же непонятно как расширениям сюда попасть
    /// <summary>
    /// Нет проблем и пометок — обычная строка.
    /// </summary>
    None,
    
    /// <summary>
    /// Строка содержит ошибку валидации или диагностики.
    /// </summary>
    Error,
    
    /// <summary>
    /// Строка содержит предупреждение валидации или диагностики.
    /// </summary>
    Warning,
    
    /// <summary>
    /// Строка помечена диагностикой расширения как «обновление».
    /// </summary>
    Update,
    
    /// <summary>
    /// Строка помечена к удалению (есть комментарий).
    /// </summary>
    Marked,
}